#: 这些词只表示镜头角度，不参与姿态展开
ANGLE_WORDS = {"正面", "侧面", "背面", "半侧面", "仰视", "俯视", "低角度", "高角度"}

_SPLIT = re.compile(r"[・·/、,，;；|]+")


def expand_pose_name(name: str) -> str:
    """把「双手扶腰・单膝内收后仰」展开为部位级描述串。

    未命中词典的短语原样保留（例如「单腿后撤」），保证不会凭空编造。
    """
    if not name:
        return ""
    parts = [p.strip() for p in _SPLIT.split(name) if p.strip()]
    out: list[str] = []
    for part in parts:
        if part in ANGLE_WORDS:
            continue
        desc = None
        # 长词优先匹配，避免「单手」吃掉「单手支撑」
        for key in sorted(PHRASES, key=len, reverse=True):
            if key in part:
                desc = PHRASES[key]
                break
        out.append(desc if desc else part)
    seen: set[str] = set()
    uniq: list[str] = []
    for s in out:
        if s and s not in seen:
            seen.add(s)
            uniq.append(s)
    return "；".join(uniq)